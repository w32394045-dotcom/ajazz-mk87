const DICTS = { zh, en };
const LANGS = [
  { id: 'zh', label: '简体中文', flag: '中' },
  { id: 'en', label: 'English', flag: 'EN' },
];

export class I18n {
  constructor(lang = 'zh') {
    this.lang = DICTS[lang] ? lang : 'zh';
    this.listeners = new Set();
  }
  t(key, vars) {
    const dict = DICTS[this.lang] || zh;
    let s = dict[key] ?? zh[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  }
  setLang(lang) {
    if (!DICTS[lang] || lang === this.lang) return false;
    this.lang = lang;
    for (const fn of this.listeners) fn(lang);
    return true;
  }
  onChange(fn) { this.listeners.add(fn); return () => this.listeners.delete(fn); }
  get languages() { return LANGS; }
}
